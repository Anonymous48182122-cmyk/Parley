// Markets that predate country codes: a saved debate or a curated ticker only knows US or India.
export function countryFor(item) {
  // a country that is present but empty means "not known": it must not be guessed from the market
  if (item && "country" in item) return item.country || null;
  const market = item?.market;
  return market === "India" ? "IN" : market === "US" ? "US" : null;
}
